  /* ---------- اتصال به چرخه رندر داشبورد ---------- */
  function hook() {
    /* هر بار داشبورد دوباره رندر کرد، توضیح‌ها را بازسازی کن */
    if (typeof window.render === 'function' && !window.render.__edu) {
      var orig = window.render;
      var wrapped = function () {
        var r = orig.apply(this, arguments);
        setTimeout(render, 30);
        return r;
      };
      wrapped.__edu = true;
      window.render = wrapped;
    }
    /* شبکه ایمنی: تغییرات DOM را هم رصد کن */
    var timer = null;
    var mo = new MutationObserver(function (muts) {
      for (var i = 0; i < muts.length; i++) {
        var m = muts[i];
        for (var j = 0; j < m.addedNodes.length; j++) {
          var n = m.addedNodes[j];
          if (n.nodeType === 1 && n.getAttribute && n.getAttribute('data-edu')) return;
        }
      }
      if (!ON) return;
      clearTimeout(timer);
      timer = setTimeout(render, 250);
    });
    mo.observe(document.body, { childList: true, subtree: true });
  }

  window.__eduRender = render;

