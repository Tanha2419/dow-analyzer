  function num(x) { return (typeof x === 'number' && isFinite(x)) ? x : null; }
  function pick() {
    for (var i = 0; i < arguments.length; i++) {
      var v = arguments[i];
      if (v !== undefined && v !== null && v !== '') return v;
    }
    return null;
  }
