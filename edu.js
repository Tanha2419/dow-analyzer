  function boxHTML(L, D) {
    var live = '';
    if (L.live) {
      try { live = L.live(D) || ''; } catch (e) { live = ''; }
    }
    return '' +
      '<div class="edu-box" data-edu="1">' +
      '<div class="edu-t">💡 ' + L.title + '</div>' +
      '<div class="edu-b">' + L.body + '</div>' +
      (live ? '<div class="edu-live"><div class="edu-lt">📌 وضعیت همین حالا</div>' + live + '</div>' : '') +
      '</div>';
  }

  function clear() {
    var old = document.querySelectorAll('[data-edu="1"]');
    for (var i = 0; i < old.length; i++) old[i].parentNode.removeChild(old[i]);
  }

  function render() {
    clear();
    if (!ON) return;
    var D = window.DATA || {};
    var CUR = (typeof window.ASSET === 'string') ? window.ASSET
            : ((D.meta && D.meta.asset) || 'US30');
    for (var i = 0; i < LESSONS.length; i++) {
      var L = LESSONS[i];
      /* درس مخصوص یک دارایی، برای بقیه نمایش داده نمی شود */
      if (L.only && L.only !== CUR) continue;
      if (L.not && L.not === CUR) continue;
      var el = document.querySelector(L.sel);
      if (!el) continue;
      /* اگر ظرف tbody است، بعد از کل جدول درج شود */
      var anchor = el;
      if (el.tagName === 'TBODY') {
        var t = el.closest ? el.closest('table') : null;
        if (t) anchor = t;
      }
      var host = anchor.parentNode;
      if (!host) continue;
      var div = document.createElement('div');
      div.innerHTML = boxHTML(L, D);
      var node = div.firstChild;
      if (anchor.nextSibling) host.insertBefore(node, anchor.nextSibling);
      else host.appendChild(node);
    }
  }

